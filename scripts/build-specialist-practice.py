def char_width(ch):
    return 1.0 if unicodedata.east_asian_width(ch) in ('W', 'F') else .59


def wrap_text(value, width, font=30):
    """Conservative CJK/Latin wrapping; every emitted line fits its cell."""
    lines = []
    for para in str(value).split('\n'):
        line = ''
        used = 0.0
        for token in re.findall(r'[A-Za-z0-9_]+|.', para):
            cw = sum(char_width(ch) * font for ch in token)
            if cw > width:
                # No authored token exceeds a full cell; catch regressions.
                raise ValueError(f'Unbreakable token too wide: {token}')
            if line and used + cw > width:
                lines.append(line)
                line, used = '', 0.0
            line += token
            used += cw
        lines.append(line)
    return lines


def render_svg(d, label):
    width, margin, content_width = 800, 30, 740
    nodes = []
    def rect(x, y, w, h, fill, radius=0, stroke='none'):
        nodes.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{radius}" fill="{fill}" stroke="{stroke}"/>')
    def txt(value, x, y, maxwidth, font=30, fill='#142b40', weight='400'):
        lines = wrap_text(value, maxwidth, font)
        for i,line in enumerate(lines):
            assert sum(char_width(c)*font for c in line) <= maxwidth + .01
            nodes.append(f'<text x="{x}" y="{y+i*(font+10)}" font-size="{font}" fill="{fill}" font-weight="{weight}">{html.escape(line)}</text>')
        return len(lines)*(font+10)
    y = 45
    y += txt(label, margin, y, content_width, 22, '#4f6576') + 8
    y += txt(d['title'], margin, y, content_width, 34, '#102c44', '700') + 20
    if d['kind'] == 'flow':
        for index,row in enumerate(d['rows']):
            label_lines = wrap_text(row[0], 620, 27)
            value = ' · '.join(str(x) for x in row[1:])
            val_lines = wrap_text(value, 620, 30)
            height = 24 + len(label_lines)*37 + 8 + len(val_lines)*40 + 22
            rect(margin,y,content_width,height,'#edf5fa',14,'#b9cedd')
            rect(margin+16,y+22,42,42,'#156b8c',21)
            txt(str(index+1), margin+28, y+52, 30, 25, '#ffffff','700')
            txt(row[0],margin+76,y+40,620,27,'#156b8c','700')
            txt(value,margin+76,y+40+len(label_lines)*37+8,620,30)
            y += height
            if index < len(d['rows'])-1:
                # Explicit polygon arrow; 28px wide and 18px high, visible when scaled.
                nodes.append(f'<path d="M400 {y+5} V{y+23}" stroke="#156b8c" stroke-width="5"/>')
                nodes.append(f'<polygon points="386,{y+20} 414,{y+20} 400,{y+38}" fill="#156b8c"/>')
                y += 46
        y += 24
    else:
        cols = len(d['headers'])
        if cols == 2:
            col_widths = [225,515]
        elif cols == 3:
            col_widths = [200,230,310]
        else:
            col_widths = [200]+[180]*(cols-1)
        assert sum(col_widths)==content_width
        allrows = [d['headers']] + d['rows']
        for ridx,row in enumerate(allrows):
            assert len(row)==cols
            font = 28 if ridx==0 else 30
            max_lines = max(len(wrap_text(value, cw-30, font)) for value,cw in zip(row,col_widths))
            rh = max_lines*(font+10)+30
            rect(margin,y,content_width,rh,'#153e58' if ridx==0 else ('#eef5f9' if ridx%2 else '#ffffff'))
            x = margin
            for value,cw in zip(row,col_widths):
                txt(value,x+15,y+font+13,cw-30,font,'#ffffff' if ridx==0 else '#142b40','700' if ridx==0 else '400')
                x += cw
            nodes.append(f'<path d="M{margin} {y+rh} H{width-margin}" stroke="#cad9e3" stroke-width="1"/>')
            y += rh
        y += 28
    if d['note']:
        lines = wrap_text(d['note'], content_width-32, 26)
        rect(margin,y,content_width,len(lines)*36+32,'#fff5df',12)
        txt(d['note'],margin+16,y+34,content_width-32,26,'#604a1d')
        y += len(lines)*36+50
    y += 8
    desc = d['title']+'。欄位依序為：'+'、'.join(d['headers'])+'。'+'；'.join('：'.join(str(v) for v in row) for row in d['rows'])+'。'+d['note']
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{int(y)}" viewBox="0 0 {width} {int(y)}" role="img" aria-labelledby="title desc"><title id="title">{html.escape(d["title"])}</title><desc id="desc">{html.escape(desc)}</desc><rect width="100%" height="100%" fill="#ffffff"/><g font-family="PingFang TC, Noto Sans CJK TC, Microsoft JhengHei, sans-serif">'+''.join(nodes)+'</g></svg>\n'
    ET.fromstring(svg)
    return svg, desc


